#!/usr/bin/env python3
"""Generate ceangal/src/emoji_data.almd: which code points are emoji by
default (Emoji_Presentation) and which can become emoji
(Extended_Pictographic), from Unicode's emoji-data.txt.

Usage:  python3 tools/gen_emoji.py <dir with emoji-data.txt>
(https://www.unicode.org/Public/16.0.0/ucd/emoji/)
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def ranges(path, prop):
    cps = set()
    for line in open(path, encoding="utf-8"):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        r, p = [s.strip() for s in line.split(";")]
        if p != prop:
            continue
        a, _, b = r.partition("..")
        cps.update(range(int(a, 16), int(b or a, 16) + 1))
    out = []
    for cp in sorted(cps):
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def packed(name, rs, doc):
    # first and last as 5 hex digits each (a string costs far less wasm than a list of tuples)
    p = "".join("%05X%05X" % tuple(r) for r in rs)
    body = "\n".join('  "%s" +' % p[i:i + 100] for i in range(0, len(p), 100)).rstrip(" +")
    return f"// {doc}\npub let {name} =\n{body}\n"


def main():
    src = os.path.join(sys.argv[1] if len(sys.argv) > 1 else ".", "emoji-data.txt")
    pres = ranges(src, "Emoji_Presentation")
    pict = ranges(src, "Extended_Pictographic")
    text = ("// Generated by tools/gen_emoji.py from Unicode 16.0 emoji-data.txt. Do not edit.\n"
            "// Ranges of code points, each 10 hex digits: first and last, 5 each.\n\n"
            + packed("PRESENTATION", pres, "Shown as emoji by default (Emoji_Presentation).") + "\n"
            + packed("PICTOGRAPHIC", pict, "Can be shown as emoji: with U+FE0F, or inside a sequence (Extended_Pictographic)."))
    dst = os.path.join(ROOT, "ceangal", "src", "emoji_data.almd")
    open(dst, "w").write(text)
    print(f"{os.path.relpath(dst, ROOT)}: {len(pres)} + {len(pict)} ranges")


if __name__ == "__main__":
    main()
